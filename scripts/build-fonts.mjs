#!/usr/bin/env node
// Self-hosted fonts (owner decision, 6 Nov 2026): the app's typefaces are served from our own server, not
// Google Fonts, so visitors' addresses go to no third party and the strict Content-Security-Policy holds.
// Writes public/fonts/{app,themes,print-kit}.css plus the font files and their OFL licences, from the pinned
// @fontsource packages (the same Google Fonts files, packaged under the SIL Open Font Licence). The family
// names stay the ones the app's styles use ('Inter', 'Fraunces', ...), so nothing else changes.
// Run by `npm run dev`, `npm run build` and `npm run build:realauth`; public/fonts is generated, not committed.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'public', 'fonts');

// [package, stylesheets, family name used by the app]. Axes match what the app asked Google Fonts for.
const SETS = {
  // Loaded on every page (was the @import at the top of src/index.css).
  app: [
    ['@fontsource-variable/inter', ['opsz.css'], 'Inter'],
    ['@fontsource-variable/fraunces', ['opsz.css'], 'Fraunces'],
    ['@fontsource/instrument-serif', ['400.css'], 'Instrument Serif'],
    ['@fontsource-variable/newsreader', ['opsz.css'], 'Newsreader'],
    ['@fontsource-variable/archivo', ['wdth.css'], 'Archivo'],
    ['@fontsource-variable/lora', ['wght.css'], 'Lora'],
    ['@fontsource-variable/cormorant-garamond', ['wght.css'], 'Cormorant Garamond'],
    ['@fontsource-variable/bricolage-grotesque', ['opsz.css'], 'Bricolage Grotesque']
  ],
  // Extra Signature-theme faces (src/data/themeFonts.ts); only pages whose theme uses one load this file.
  themes: [
    ['@fontsource-variable/manrope', ['wght.css'], 'Manrope'],
    ['@fontsource-variable/sora', ['wght.css'], 'Sora'],
    ['@fontsource/dm-serif-display', ['400.css'], 'DM Serif Display'],
    ['@fontsource-variable/playfair-display', ['wght.css'], 'Playfair Display'],
    ['@fontsource-variable/outfit', ['wght.css'], 'Outfit'],
    ['@fontsource-variable/syne', ['wght.css'], 'Syne']
  ],
  // The printable kit's documents (src/utils/domains/printKitTemplates.ts).
  'print-kit': [
    ['@fontsource-variable/inter', ['opsz.css'], 'Inter'],
    ['@fontsource/libre-baskerville', ['400.css', '700.css'], 'Libre Baskerville'],
    ['@fontsource-variable/nunito', ['wght.css'], 'Nunito'],
    ['@fontsource-variable/playfair-display', ['wght.css'], 'Playfair Display']
  ]
};

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });
mkdirSync(join(out, 'licences'), { recursive: true });
const copied = new Set();

for (const [name, entries] of Object.entries(SETS)) {
  let css = `/* Generated by scripts/build-fonts.mjs from @fontsource packages (SIL Open Font Licence; see /fonts/licences). */\n`;
  for (const [pkg, sheets, family] of entries) {
    const dir = join(root, 'node_modules', pkg);
    if (!existsSync(dir)) throw new Error(`build-fonts: ${pkg} is not installed (npm ci)`);
    for (const sheet of sheets) {
      const source = readFileSync(join(dir, sheet), 'utf8');
      css += source
        .replace(/font-family:\s*'[^']+';/g, `font-family: '${family}';`)
        .replace(/url\(\.\/files\/([\w.-]+)\)/g, (_m, file) => {
          if (!copied.has(file)) {
            copyFileSync(join(dir, 'files', file), join(out, 'files', file));
            copied.add(file);
          }
          return `url(/fonts/files/${file})`;
        });
    }
    const licence = ['LICENSE', 'LICENSE.md', 'OFL.txt'].map((f) => join(dir, f)).find((f) => existsSync(f));
    if (!licence) throw new Error(`build-fonts: no licence file in ${pkg}`);
    copyFileSync(licence, join(out, 'licences', `${pkg.replace(/[@/]/g, '_').replace(/^_/, '')}.txt`));
  }
  if (/fonts\.(googleapis|gstatic)\.com/.test(css)) throw new Error('build-fonts: a stylesheet still points at Google Fonts');
  writeFileSync(join(out, `${name}.css`), css);
}
console.log(`build-fonts: wrote public/fonts (${Object.keys(SETS).join(', ')}; ${copied.size} font files)`);
